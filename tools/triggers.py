"""LLM 工具描述的「唤醒约定」：什么时候才允许调用本插件。

为什么需要单独一份约定
----------------------
本插件的 9 个工具靠描述文本被模型选中，而「比赛」「战绩」「出装」这类词在
群聊里会被大量其他游戏与体育话题触发。如果不写清唤醒条件，会出现两类事故：

1. **该唤醒却不唤醒**：用户说「分析比赛 8987081176」，模型以为是足球赛果预测
   而拒答（真实事故，已修过一次）；
2. **不该唤醒却唤醒**：用户说「分析一下比赛」或聊王者荣耀/英雄联盟，插件插话
   返回 Dota2 数据。

因此统一约定：**必须出现刀塔标识、8~10 位比赛编号、或明确的 Dota2 英雄名，
三者任一才唤醒**。这样既能与未来其他游戏查询插件区分开，又保留了编号、
英雄名这类高区分度问法（它们本身就只可能指向 Dota2）。

措辞刻意压缩：9 个工具都要带上这段，每多 50 字就等于多付 9 份上下文预算。
"""

from __future__ import annotations

# 唤醒条件。放在每个工具描述最前面，措辞保持一致，便于模型形成稳定判断。
WAKE_RULE = (
    "【唤醒】用户消息出现以下任一信号才调用："
    "①刀塔标识（刀塔/刀塔2/刀塔二/dota/dota2）；"
    "②8~10 位纯数字的比赛编号（如 8987081176）；"
    "③明确的刀塔英雄名（如敌法师、影魔、水人、火猫、剑圣）。"
    "三者都没有时不要调用——若用户只说「分析比赛」「查战绩」「怎么出装」，"
    "先反问是不是要查「刀塔比赛」。"
)

# 适用范围。一次性排除其他游戏与体育赛事，避免误判。
SCOPE_RULE = (
    "【范围】只查 Dota2（刀塔）这一款游戏；与王者荣耀、英雄联盟、CS2 等"
    "其他游戏无关，也与足球/篮球等体育赛事及赔率、盘口、投注、赛果预测无关。"
)

# 比赛类工具追加：保留原始事故的上下文。模型此前会把「分析比赛 编号」
# 当成足球赛果预测而拒答，这里显式禁止该误判。
SPORTS_MISJUDGEMENT_RULE = (
    "别因为群聊里正聊「比赛」「赔率」「盘口」就当成赛事预测而拒答——"
    "本插件只做已结束对局的查询与复盘，不涉及赛果预测。"
)
